export const MESSAGES: Record<Locale, Record<MessageKey, string>> = { en, hi };

export function isLocale(v: unknown): v is Locale {
  return typeof v === "string" && (LOCALES as readonly string[]).includes(v);
}

export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>): string {
  const s = MESSAGES[locale][key] ?? MESSAGES.en[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (_, k: string) => (k in vars ? String(vars[k]) : `{${k}}`)) : s;
}

/** Explicit ?lang= wins, then the saved cookie, then Accept-Language (Hindi first), else English. */
export function pickLocale(opts: { cookie?: string | null; query?: string | null; acceptLanguage?: string | null }): Locale {
  if (isLocale(opts.query)) return opts.query;
  if (isLocale(opts.cookie)) return opts.cookie;
  const al = (opts.acceptLanguage || "").toLowerCase();
  const first = al.split(",")[0]?.trim() ?? "";
  return first.startsWith("hi") ? "hi" : "en";
}

/** Hindi status words for deal statuses. */
export function statusLabel(locale: Locale, s: "active" | "completed" | "cancelled"): string {
  return translate(locale, `status.${s}` as MessageKey);
}
